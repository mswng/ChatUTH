    Chuyên ngành Xây dựng cầu đường là một trong những ngành đào tạo chủ lực của Viện Xây dựng trong hơn 20 năm qua. Các giảng viên ngành Cầu Đường là những người thầy đầy tâm huyết với sinh viên và có trình độ chuyên môn cao, hơn 80% giảng viên có trình độ Tiến sỹ và được đào tạo từ các nước phát triển như Anh, Pháp, Đức, Nga, Hàn Quốc… Vì vậy, trong suốt thời gian qua, sinh viên sau khi tốt nghiệp có thể tự tin tìm việc đúng chuyên ngành đã được học, nhiều sinh viên trường đã trở thành các Kỹ sư có trình độ chuyên môn cao và cán bộ nồng cốt trong các công ty tư vấn, sở ban ngành … đặc biệt là khu vực Miền Trung và phía Nam. Nhiều sinh viên đã trở thành các nhà nghiên cứu khoa học mang tầm quốc tế ở các trường đại học lớn, các viện nghiên cứu trên thế giới như Đại học Bristol (Anh Quốc), Đại học New South Wales (Úc), Đại học Luân Đôn (Anh Quốc), … Theo khảo sát tình hình tìm việc làm của SV sau khi tốt nghiệp trong những năm gần đây (2017 đến 2018): Đối với các ngành thuộc Khoa CTGT thì có đến 94% SV có việc làm đúng chuyên ngành, và riêng ngành Cầu Đường là 100% (theo Báo cáo số 891/BC-ĐHGTVT/2018).

    UTH luôn có chiến lược xây dựng chương trình đào tạo, đầu tư cơ sở vật chất, tài liệu học tập, phòng thí nghiệm đầy đủ để phục vụ cho sinh viên có được môi trường học tập tốt nhất để SV sau khi tốt nghiệp ngành Cầu Đường không những đạt trình độ cao đúng chuyên ngành của mình mà còn có khả năng thích nghi làm việc ở nhiều ngành thuộc lĩnh vực khác như: Xây dựng dân dụng và công nghiệp, Thủy lợi, Cảng công trình biển, …

🟥 Cơ hội việc làm    

    Các công việc sinh viên có thể tham gia sau khi tốt nghiệp bao gồm: khảo sát và tư vấn thiết kế; tư vấn đầu tư trong lĩnh vực Xây dựng cho các tổ chức tín dụng; tư vấn giám sát; quản lý dự án; thi công công trình; công tác nghiên cứu tại các Trường ĐH, các Viện nghiên cứu trong và ngoài nước; …

    Việc phát triển giao thông vận tải, đặc biệt là lĩnh vực Cầu Đường, có ý nghĩa quan trọng để tạo nền tảng thúc đẩy phát triển kinh tế xã hội. Vì vậy vốn đầu tư cho ngành luôn chiếm tỷ trọng lớn trong nguồn vốn đầu tư từ ngân sách Nhà nước. Năm 2016 nguồn vốn cho Bộ Giao thông chiếm gần 30% trong tổng nguồn vốn của 10 Bộ ngành khác nhau, năm 2017 chiếm khoảng 50% và năm 2018 chiếm khoảng 30%. Hiện nay nhiều dự án Cầu đường mang tầm quốc gia như Dự án cao tốc Bắc Nam, Dự án vành đai ven biển … vốn lên tới hàng trăm nghìn tỉ đồng đang triển khai. Riêng tại TP. HCM, năm 2019-2020, Sở GTVT cho biết TP sẽ triển khai khoảng 138 dự án giao thông đường bộ trong thành phố như dự án đường ven sông (18277 tỉ đồng), dự án Cầu Cát Lái (339 triệu đô), cầu Cần Giờ, cầu Thủ Thiêm 4… Điều đó cho thấy tiềm năng phát triển của ngành Cầu đường là rất lớn. Đây là cơ hội cho sinh viên sau khi tốt nghiệp khẳng định giá trị bản thân, tạo nên nhiều ích lợi cho gia đình và cho xã hội.

