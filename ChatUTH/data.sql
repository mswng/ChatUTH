V. HỌC PHÍ VÀ HỌC BỔNG

5.1. Học phí

Học phí đối với sinh viên hình thức đào tạo chính quy tuyển sinh khóa tuyển sinh năm 2025 theo đơn vị tín chỉ như sau:

✓ Chương trình chuẩn: 450.000 VNĐ/tín chỉ

✓ Chương trình tiên tiến: 980.000 VNĐ/tín chỉ.

✓ Chương trình hoàn toàn bằng Tiếng Anh: 1.500.000 VNĐ/tín chỉ.

5.2. Chính sách học phí

✓ Trường cam kết không tăng học phí theo lộ trình trong 03 năm đầu tiên đối với sinh viên trúng tuyển khóa tuyển sinh năm 2025;

✓ Trường cam kết ổn định chương trình đào tạo bao gồm 120 tín chỉ; khối lượng tín chỉ tối thiểu theo quy định của Thủ tướng Chính phủ tại Quyết định số 1982/QĐ-TTg ngày 18/10/2016.

✓ Học phí chương trình tiên tiến và chương trình hoàn toàn bằng Tiếng Anh giữ nguyên như khóa tuyển sinh năm 2024.

5.3. Cách tính học phí:

5.3.1. Công thức:

Học phí toàn khóa học: 120 tín chỉ * học phí 01 tín chỉ theo loại chương trình đào tạo.

5.3.2. Chương trình chuẩn:

✓ Học phí toàn khóa học chương trình đào tạo chuẩn: 120 tín chỉ * 450.000 VNĐ = 54.000.000 VNĐ (năm mươi tư triệu đồng).

✓ Đối với sinh viên học vượt kế hoạch, tham gia cả học kỳ hè để tốt nghiệp trình độ đại học trong 03 năm: 54 triệu VNĐ.

✓ Đối với sinh viên học theo kế hoạch học tập 04 năm, hoặc học chậm so với tiến độ: Mức học phí mỗi tín chỉ tăng theo lộ trình tăng học phí Chính phủ quy định kể từ năm thứ 4.

5.3.3. Chương trình tiên tiến

✓ Học phí toàn khóa học chương trình đào tạo tiên tiến: 120 tín chỉ * 980.000 VNĐ = 117.600.000 VNĐ (một trăm mười bảy triệu sáu trăm nghìn đồng).

✓ Đối với sinh viên học vượt kế hoạch, tham gia cả học kỳ hè để tốt nghiệp trình độ đại học trong 03 năm: 117.6 triệu VNĐ.

✓ Đối với sinh viên học theo kế hoạch học tập 04 năm, hoặc học chậm so với tiến độ: Mức học phí mỗi tín chỉ tăng theo lộ trình tăng học phí Chính phủ quy định kể từ năm thứ 4.

5.3.4. Chương trình hoàn toàn bằng Tiếng Anh

