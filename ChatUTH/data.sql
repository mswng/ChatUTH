✅ Hệ thống điện và điện tử ô tô: Bao gồm các học phần về điện tử ô tô, vi điều khiển, mạng xe ô tô, hệ thống giám sát và kiểm soát, cảm biến và hệ thống thông tin và giải trí trong xe.

✅ Công nghệ điều khiển và tự động hóa: Học về các công nghệ tự động hóa trong ô tô, bao gồm hệ thống lái tự động, cảm biến và hệ thống kiểm soát tự động.

✅ Công nghệ xử lý hình ảnh và nhận dạng: Đào tạo về công nghệ nhận dạng hình ảnh và các ứng dụng trong hệ thống lái tự động và hỗ trợ lái.

✅ An toàn ô tô và tiêu chuẩn quốc tế: Học về các tiêu chuẩn an toàn ô tô, bao gồm hệ thống phanh, hệ thống túi khí, hệ thống tránh va chạm và các quy định quốc tế liên quan.

✅ Phát triển phần mềm và hệ thống: Đào tạo về phát triển phần mềm trong xe ô tô, bao gồm phát triển ứng dụng điện tử và phần mềm cho hệ thống giải trí, định vị, và các tính năng khác.

