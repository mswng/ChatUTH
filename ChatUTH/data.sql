    Chương trình được thiết kế với mục tiêu đạo tạo cử nhân ngành Kỹ thuật xây dựng công trình giao thông có khả năng sau:

✔️ Áp dụng kiến thức khoa học cơ bản cho việc tiếp thu các kiến thức giáo dục chuyên nghiệp; hiểu rõ về sự cần thiết phải học tập suốt đời;

✔️ Tổng hợp các kiến thức cơ sở ngành và chuyên ngành để giải quyết các vấn đề liên quan đến kỹ thuật xây dựng Đường sắt tốc độ cao và Đường sắt đô thị;

✔️ Có các kỹ năng cá nhân, nghề nghiệp, giao tiếp và làm việc nhóm;

✔️ Hiểu các vấn đề kinh tế, chính trị; có đạo đức nghề nghiệp; biết trách nhiệm với xã hội để đóng góp hữu hiệu vào sự phát triển bền vững của cộng đồng và xã hội.

