    Viện Xây dựng có đội ngũ giảng viên tâm huyết với nghề nghiệp và có trình độ chuyên môn cao với hơn 70% là tiến sĩ đảm nhiệm đào tạo sinh viên chuyên ngành Xây dựng Công trình giao thông đô thị. Trên cơ sở “Đào tạo theo yêu cầu của xã hội” và “Lấy người học làm trung tâm”, chương trình đào tạo cử nhân Xây dựng Công trình giao thông đô thị được xây dựng bài bản theo phương pháp hiện đại. Với mục tiêu đào tạo ra những cử nhân không chỉ có trình độ cao về chuyên môn mà còn thành thạo những kỹ năng mềm, sinh viên sau khi tốt nghiệp có thể thích ứng nhanh với môi trường làm việc chuyên nghiệp và có khả năng đảm nhận công việc của các ngành gần. Cử nhân chuyên ngành Xây dựng Công trình giao thông đô thị có thể đảm nhận các vị trí công việc sau: Khảo sát và tư vấn thiết kế, Tư vấn giám sát, Quản lý dự án, Thi công các dạng công trình: Cầu hầm đường sắt đô thị, Nhà ga Metro, Cầu đường ô tô trong đô thị, Hầm giao thông, Hạ tầng kỹ thuật đô thị, Công trình dân dụng và công nghiệp, …

